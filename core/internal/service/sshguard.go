// SshGuardService SSH 安全（M49）：sshd 配置管理（端口/认证开关/root 策略）+ 登录日志 + 暴力破解防护联动。
// 修改走 99-ypanel.conf（Ubuntu Include 优先）+ sshd -t 校验 + reload（不断开现有连接）。
