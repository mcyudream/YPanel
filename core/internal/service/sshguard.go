// SshGuardService SSH 安全（M49/M53）：sshd 配置管理（端口/认证开关/root 策略）+ 密钥统一管理 + 登录日志 + 暴力破解防护联动。
// 全部操作按 nodeID 走对应节点 agent 通道（local / 远程同构）。
// 配置修改写 00-ypanel.conf：sshd_config 首值生效（first-value-wins），Include 文件按字典序读取，
// 00- 前缀保证压过 50-cloud-init.conf 等发行版预置文件（99- 前缀曾被抢先生效值静默覆盖，见 M53 计划）。
// 写入后 sshd -t 校验（失败自动回滚）+ reload（不中断现有连接）。
